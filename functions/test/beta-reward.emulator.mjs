import '../lib/index.js';
import test from 'node:test';
import assert from 'node:assert/strict';
import {getFirestore} from 'firebase-admin/firestore';
import {activateReward, rewardStatus, BETA_DAYS} from '../lib/betaReward.js';
import {webEntitlement} from '../lib/webEntitlement.js';
import {trialEligible} from '../lib/webTrial.js';
import {fakeAuth} from './_paymongo-helpers.mjs';
const db=getFirestore(), uid='reward-integration', start=Date.parse('2026-11-15T12:00:00+08:00');
const auth={uid,token:{email:'reward@example.com',email_verified:true,firebase:{sign_in_provider:'google.com',identities:{'google.com':['reward-google']}}}};
const request={auth,app:{appId:'test'},data:{}};
test('queued reward claims refresh on discovery and reward grants never consume a trial',async()=>{
 await db.recursiveDelete(db.doc(`users/${uid}`));
 await db.doc('betaApplications/reward-integration').set({email:'reward@example.com',selected:true});
 await db.doc(`users/${uid}/betaReward/state`).set({days:BETA_DAYS,surveyAt:start});
 const end=start+86400000, claimAuth=fakeAuth(), deps={db,auth:claimAuth,allow:async()=>true,now:()=>start};
 await db.doc(`users/${uid}/grants/paid`).set({source:'paymongo',product:'pantas_cs_monthly',tier:'civilService',startsAt:start-1,endsAt:end,state:'active',createdAt:start});
 const [first, second]=await Promise.all([activateReward(request,deps),activateReward(request,{...deps,auth:undefined})]);
 assert.deepEqual(first,second);
 assert.equal((await db.collection(`users/${uid}/grants`).get()).size,19);
 const before=(await db.doc(`users/${uid}/server/entitlement`).get()).get('version');
 await webEntitlement(auth,db,end,claimAuth);
 await rewardStatus(request,{...deps,now:()=>end});
 assert.ok((await db.doc(`users/${uid}/server/entitlement`).get()).get('version')>before);
 assert.equal(claimAuth.current().pro,true);assert.equal(claimAuth.current().proUntil,first.endsAt);
 assert.equal((await webEntitlement(auth,db,end)).grants.filter(g=>g.source==='beta_reward').length,18);
 await db.doc(`users/${uid}/grants/paid`).delete();
 process.env.TRIAL_IDENTITY_HMAC_KEY='test-only-reward-secret';
 assert.equal(await trialEligible(auth,db),true);
});
