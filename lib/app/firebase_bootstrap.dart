import 'package:cse_cet_reviewer/app/flavor.dart';

enum AppCheckProvider { debug, playIntegrity }

class FirebaseAppConfig {
  const FirebaseAppConfig({required this.name});

  final String name;
}

abstract interface class FirebaseBootAdapter {
  Future<void> initialize(FirebaseAppConfig config);

  Future<void> activateAppCheck(AppCheckProvider provider);
}

typedef FirebaseConfigSelector = FirebaseAppConfig? Function(Flavor flavor);

FirebaseAppConfig? firebaseConfigForFlavor(Flavor flavor) {
  return null;
}

Future<void> bootstrapFirebase(
  Flavor flavor, {
  FirebaseBootAdapter adapter = const FirebaseSdkBootAdapter(),
  FirebaseConfigSelector configSelector = firebaseConfigForFlavor,
}) async {
  final config = configSelector(flavor);
  if (config == null) return;

  await adapter.initialize(config);
  await adapter.activateAppCheck(_appCheckProviderForFlavor(flavor));
}

AppCheckProvider _appCheckProviderForFlavor(Flavor flavor) {
  return switch (flavor) {
    Flavor.prod => AppCheckProvider.playIntegrity,
    Flavor.dev || Flavor.staging => AppCheckProvider.debug,
  };
}

class FirebaseSdkBootAdapter implements FirebaseBootAdapter {
  const FirebaseSdkBootAdapter();

  @override
  Future<void> initialize(FirebaseAppConfig config) async {
    // Real options are generated by flutterfire configure and wired in after
    // the Firebase projects exist.
  }

  @override
  Future<void> activateAppCheck(AppCheckProvider provider) async {
    // Activation is intentionally skipped until generated Firebase options are
    // available. Tests cover provider selection through the injected adapter.
  }
}
