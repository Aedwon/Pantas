#!/usr/bin/env bash
# Compiles the server entry to one JS module and copies it into functions.
# Run from anywhere. Needs the Dart SDK and, once per checkout,
#   flutter pub get && dart run build_runner build --delete-conflicting-outputs
# (a freezed file is in the import closure).
#
#   server_dart/build.sh           rebuild functions/src/generated/pantas_core.js
#   server_dart/build.sh --check   rebuild to a temp file and fail if it differs
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/functions/src/generated/pantas_core.js"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
cd "$ROOT"
dart compile js -O4 -o "$TMP/core.js" server_dart/pantas_core.dart >/dev/null
{
  echo "// Generated by server_dart/build.sh. Do not edit. Source hash below covers every Dart file compiled in."
  echo "// pantas-core-source-hash: $(node server_dart/closure_hash.mjs)"
  cat "$TMP/core.js"
} > "$TMP/pantas_core.js"
if [ "${1:-}" = "--check" ]; then
  cmp -s "$TMP/pantas_core.js" "$OUT" || { echo "STALE: $OUT differs from a fresh build. Run server_dart/build.sh"; exit 1; }
  echo "generated JS is current"
else
  mkdir -p "$(dirname "$OUT")"
  cp "$TMP/pantas_core.js" "$OUT"
  echo "wrote $OUT ($(wc -c < "$OUT") bytes, $(gzip -9 -c "$OUT" | wc -c) gzip)"
fi
