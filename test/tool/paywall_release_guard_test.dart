import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

void main() {
  test('FAKE_PRO appears only in debug guarded paywall provider code', () {
    final offenders = <String>[];
    var foundGuardedFlag = false;
    for (final file in _dartFiles('lib')) {
      final source = file.readAsStringSync();
      if (!source.contains('FAKE_PRO')) continue;
      final allowed = file.path.endsWith(
              'lib/features/paywall/application/paywall_providers.dart') &&
          source.contains('kDebugMode') &&
          source.contains("bool.fromEnvironment('FAKE_PRO')");
      if (allowed) foundGuardedFlag = true;
      if (!allowed) offenders.add(file.path);
    }

    expect(offenders, isEmpty);
    expect(foundGuardedFlag, isTrue);
  });

  test('paywall files do not contain tool model or vendor attribution strings',
      () {
    final offenders = <String>[];
    final forbidden = RegExp(
      r'(generated by|AI-generated|model attribution|tool attribution)',
      caseSensitive: false,
    );
    for (final file in [
      ..._dartFiles('lib/features/paywall'),
      ..._dartFiles('test/features/paywall'),
    ]) {
      if (forbidden.hasMatch(file.readAsStringSync())) {
        offenders.add(file.path);
      }
    }

    expect(offenders, isEmpty);
  });
}

Iterable<File> _dartFiles(String path) {
  final dir = Directory(path);
  if (!dir.existsSync()) return const [];
  return dir
      .listSync(recursive: true)
      .whereType<File>()
      .where((file) => file.path.endsWith('.dart'));
}
