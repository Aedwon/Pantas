import 'package:flutter_test/flutter_test.dart';
// Path import: the tool is not part of lib/, so import by relative file path.
import '../../tool/check_no_ai_attribution.dart';

void main() {
  group('attribution markers are banned everywhere', () {
    test('a co-authored trailer naming a vendor is a hit', () {
      expect(scanText('README.md', 'Co-Authored-By: Claude <x@y.z>'), isNotEmpty);
      expect(scanText('README.md', 'co-authored-by: ai'), isNotEmpty);
    });

    test('a generated-with line is a hit', () {
      expect(scanText('README.md', 'Generated with Claude Code'), isNotEmpty);
      expect(scanText('README.md', 'generated by an AI assistant'), isNotEmpty);
    });

    test('the robot marker is a hit', () {
      expect(scanText('README.md', 'Robot: \u{1F916} Generated with'), isNotEmpty);
    });

    test('an authored-by attribution is a hit', () {
      expect(scanText('docs/x.md', 'Written by Claude.'), isNotEmpty);
      expect(scanText('docs/x.md', 'Assisted by Anthropic tooling'), isNotEmpty);
    });
  });

  group('bare vendor names are banned in code and content', () {
    test('a vendor name in lib/ is a hit', () {
      expect(scanText('lib/app/app.dart', '// ask claude about this'), isNotEmpty);
    });

    test('a vendor name in content/ is a hit', () {
      expect(scanText('content/lessons/x.md', 'Anthropic'), isNotEmpty);
    });

    test('a vendor name in prose documentation is not a hit', () {
      // Docs legitimately name the instruction file and state the rule.
      expect(scanText('docs/superpowers/x.md', 'See CLAUDE.md.'), isEmpty);
    });
  });

  group('the two long-standing false positives are gone', () {
    test('naming the instruction file is never a hit', () {
      expect(scanText('AGENTS.md', 'read `CLAUDE.md` as well'), isEmpty);
      expect(scanText('SUBAGENTS.md', 'CLAUDE.md governs design'), isEmpty);
      // Even inside lib/, the filename is a legitimate reference.
      expect(scanText('lib/x.dart', '// See CLAUDE.md'), isEmpty);
    });

    test('stating the prohibition is never a hit', () {
      expect(
        scanText('docs/superpowers/plans/p.md',
            '- No AI/Claude attribution in any commit message.'),
        isEmpty,
      );
      expect(
        scanText('docs/x.md', 'Do not add a Co-Authored-By: Claude trailer.'),
        isEmpty,
      );
    });
  });

  group('commit messages are scanned, which files could not cover', () {
    test('a trailer in a commit message is a hit', () {
      expect(
        scanCommitMessage('abc1234', 'fix: thing\n\nCo-Authored-By: Claude'),
        isNotEmpty,
      );
    });

    test('naming the instruction file in a commit message is not a hit', () {
      expect(
        scanCommitMessage('abc1234', 'docs: CLAUDE.md is how to design'),
        isEmpty,
      );
    });

    test('stating the rule in a commit message is not a hit', () {
      expect(
        scanCommitMessage('abc1234', 'chore: ban Co-Authored-By: Claude trailers'),
        isEmpty,
      );
    });
  });

  group('scoping', () {
    test('the checker itself is exempt', () {
      expect(isExempt('tool/check_no_ai_attribution.dart'), isTrue);
    });

    test('ordinary files are not exempt', () {
      expect(isExempt('lib/app/app.dart'), isFalse);
      expect(isExempt('docs/superpowers/plans/p.md'), isFalse);
    });

    test('only files reproducing the checker are exempt', () {
      // Plan 01 quotes this checker's source in a fenced block. Every other
      // plan is scanned, which the old blanket exclusion of the whole plans
      // directory did not do.
      expect(
        isExempt('docs/superpowers/plans/2026-05-07-plan-01-foundation-and-ops.md'),
        isTrue,
      );
      expect(
        isExempt('docs/superpowers/plans/2026-08-03-offline-posture.md'),
        isFalse,
      );
    });
  });
}
