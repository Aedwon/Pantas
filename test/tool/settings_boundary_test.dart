import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

void main() {
  test(
    'settings domain files do not import framework or presentation packages',
    () {
      final offenders = <String>[];
      for (final file in _dartFiles('lib/features/settings/domain')) {
        final source = file.readAsStringSync();
        final hasForbiddenImport = source.contains('package:flutter/') ||
            source.contains('package:firebase_') ||
            source.contains('package:cloud_') ||
            source.contains('package:drift/') ||
            source.contains('package:go_router/') ||
            source.contains('/presentation/');
        if (hasForbiddenImport) offenders.add(file.path);
      }

      expect(offenders, isEmpty);
    },
  );

  test('settings feature does not import content database or content sync', () {
    final offenders = <String>[];
    for (final file in _dartFiles('lib/features/settings')) {
      final source = file.readAsStringSync();
      if (source.contains('/core/content/') ||
          source.contains('ContentDatabase') ||
          source.contains('ContentSyncCoordinator')) {
        offenders.add(file.path);
      }
    }

    expect(offenders, isEmpty);
  });

  test('content database does not contain user settings tables', () {
    final offenders = <String>[];
    for (final file in _dartFiles('lib/core/content')) {
      final source = file.readAsStringSync();
      if (source.contains('UserSettings') ||
          source.contains('AccountPrefs') ||
          source.contains('DevicePrefs')) {
        offenders.add(file.path);
      }
    }

    expect(offenders, isEmpty);
  });

  test('settings files do not contain tool model or vendor attribution strings',
      () {
    final forbidden = RegExp(
      '(generated by|AI-generated|model attribution|tool attribution)',
      caseSensitive: false,
    );
    final offenders = _dartFiles('lib/features/settings')
        .where((file) => forbidden.hasMatch(file.readAsStringSync()))
        .map((file) => file.path)
        .toList();

    expect(offenders, isEmpty);
  });
}

Iterable<File> _dartFiles(String path) {
  final dir = Directory(path);
  if (!dir.existsSync()) return const [];
  return dir
      .listSync(recursive: true)
      .whereType<File>()
      .where((file) => file.path.endsWith('.dart'));
}
