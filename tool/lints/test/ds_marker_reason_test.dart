import 'package:analyzer_testing/analysis_rule/analysis_rule.dart';
import 'package:pantas_lints/src/ds_marker_reason.dart';
import 'package:test_reflective_loader/test_reflective_loader.dart';

import 'support.dart';

void main() {
  defineReflectiveSuite(() {
    defineReflectiveTests(DsMarkerReasonTest);
  });
}

@reflectiveTest
class DsMarkerReasonTest extends AnalysisRuleTest with AnnotatedAsserts {
  @override
  void setUp() {
    rule = DsMarkerReason();
    super.setUp();
  }

  Future<void> test_markers_with_a_reason_are_clean() => assertNoDiagnostics('''
// ds-geometry: logo corner
// ds-board: Home board, row gap
// ds-raw: brand button with logo content
void f() {}
''');

  Future<void> test_geometry_without_a_reason() =>
      assertMarked('«// ds-geometry:»\nvoid f() {}\n');

  Future<void> test_geometry_with_only_spaces() =>
      assertMarked('«// ds-geometry:   »\nvoid f() {}\n');

  Future<void> test_board_without_a_colon() =>
      assertMarked('«// ds-board»\nvoid f() {}\n');

  Future<void> test_raw_without_a_reason() =>
      assertMarked('void f() {} «// ds-raw:»\n');

  Future<void> test_prose_that_only_mentions_a_marker_is_clean() =>
      assertNoDiagnostics('''
// The ds-geometry marker is described in the guardrails plan.
void f() {}
''');

  Future<void> test_ignore_of_a_ds_rule_without_a_reason() => assertMarked('''
void f() {
  «// ignore: ds_no_design_literal»
}
''');

  Future<void> test_ignore_of_a_ds_rule_with_a_reason() =>
      assertNoDiagnostics('''
void f() {
  // ignore: ds_no_design_literal -- prototype only, removed in the Home pass
}
''');

  Future<void> test_ignore_for_file_without_a_reason() =>
      assertMarked('«// ignore_for_file: ds_board_value_reason»\n');

  Future<void> test_ignore_for_file_with_a_reason() => assertNoDiagnostics(
    '// ignore_for_file: ds_board_value_reason -- generated by the sheet tool\n',
  );

  Future<void> test_ignore_of_another_rule_is_clean() => assertNoDiagnostics('''
void f() {
  // ignore: unused_local_variable
}
''');
}
