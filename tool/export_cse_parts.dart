import 'dart:convert';
import 'dart:io';

import 'package:pantas/core/metrics/overall_accuracy.dart';

/// Exports display data only. The server's compiled rating code stays intact.
void main(List<String> args) {
  final data = {
    for (final examId in ['exam_cse_pro', 'exam_cse_sub'])
      examId: [
        for (final part in csePartsForExam(examId))
          {'id': part.key, 'name': part.name, 'topicNames': part.topicNames},
      ],
  };
  final source = '// Generated by tool/export_cse_parts.dart. Do not edit.\n'
      'export const cseParts = '
      '${const JsonEncoder.withIndent('  ').convert(data)} as const;\n';
  final file = File('functions/src/generated/cse_parts.ts');
  if (args.contains('--check')) {
    if (!file.existsSync() || file.readAsStringSync() != source) {
      stderr.writeln('Run tool/export_cse_parts.dart to refresh CSE parts.');
      exitCode = 1;
    }
  } else {
    file.writeAsStringSync(source);
  }
}
